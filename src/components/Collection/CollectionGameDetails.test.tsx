import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { renderWithProviders } from '@/test/utils/renderWithProviders'
import { createGame } from '@/test/factories'
import i18n from '@/i18n'
import { CollectionGameDetails } from './CollectionGameDetails'

const mocks = vi.hoisted(() => ({ update: vi.fn(), get: vi.fn(), remove: vi.fn() }))
vi.mock('@/hooks/useGames/useGames', () => ({ useGames: () => ({ updateGameById: mocks.update }) }))
vi.mock('@/services/GamesService/GamesService', () => ({ getGameById: mocks.get, deleteGame: mocks.remove }))
vi.mock('@/components/elements/GameDetails/GameReplaysTab', () => ({ GameReplaysTab: ({ gameId }: { gameId: number }) => <div>Replays for {gameId}</div> }))
vi.mock('@/components/elements/GameDetails/GameHistoryTab', () => ({ GameHistoryTab: ({ gameId }: { gameId: number }) => <div>History for {gameId}</div> }))
vi.mock('@/components/elements/GameDetails/SteamTab', () => ({ SteamTab: () => <div>Retained Steam tools</div> }))
vi.mock('@/services/CollectionService/PlaylistCollectionService', () => ({ getCollectionFocus: vi.fn().mockResolvedValue(null) }))

const game = createGame({ id: 501, name: 'Pokémon Test', comment: 'Before', manualPlaytimeMinutes: 0, steamPlaytimeForever: 600, critic: 90, story: 20, score: 3, steamAppId: 100 })
const auth = { user: { id: 1, username: 'test', role: 'Admin' }, token: 'test', refreshToken: null, isAuthenticated: true, loading: false, error: null } as const
const renderDetails = (onDelete?: () => void) => renderWithProviders(<CollectionGameDetails game={game} closeDetails={vi.fn()} onDelete={onDelete} />, { preloadedState: { auth } })

describe('Gallery game details and explicit editor', () => {
	beforeEach(async () => {
		vi.clearAllMocks()
		await i18n.changeLanguage('en')
		mocks.get.mockResolvedValue(game)
		mocks.update.mockResolvedValue(game)
		mocks.remove.mockResolvedValue(undefined)
	})
	it('uses Steam when a legacy manual value is zero and keeps the existing tabs reachable', async () => {
		renderDetails()
		expect((await screen.findAllByText('10 h')).length).toBeGreaterThan(0)
		expect(screen.queryByText('0 h')).not.toBeInTheDocument()
		await userEvent.click(screen.getByRole('button', { name: 'Replays' }))
		expect(screen.getByText('Replays for 501')).toBeInTheDocument()
		await userEvent.click(screen.getByRole('button', { name: 'History' }))
		expect(screen.getByText('History for 501')).toBeInTheDocument()
		await userEvent.click(screen.getByRole('button', { name: 'Steam' }))
		expect(screen.getByText('Retained Steam tools')).toBeInTheDocument()
	})
	it('keeps the game name as the dialog name and closes through the new sheet', async () => {
		const close = vi.fn()
		renderWithProviders(<CollectionGameDetails game={game} closeDetails={close} />, { preloadedState: { auth } })
		expect(screen.getByRole('dialog', { name: game.name })).toBeInTheDocument()
		await userEvent.click(screen.getByRole('button', { name: 'Close' }))
		expect(close).toHaveBeenCalledOnce()
	})
	it('preserves a missing Hero instead of substituting the vertical Cover', async () => {
		const noHero = { ...game, hero: undefined, cover: 'https://cdn.test/cover.jpg' }
		mocks.get.mockResolvedValue(noHero)
		renderWithProviders(<CollectionGameDetails game={noHero} closeDetails={vi.fn()} />, { preloadedState: { auth } })
		await waitFor(() => expect(screen.getByRole('button', { name: 'Add to Focus' })).toBeEnabled())
		expect(document.querySelector('.gdb-detail-hero img')).not.toBeInTheDocument()
		expect(document.querySelector('.gdb-detail-cover img')).toBeInTheDocument()
	})
	it('retains the independent artwork rows and their explicit edit destinations', async () => {
		renderDetails()
		expect(document.querySelectorAll('.gdb-detail-artwork>div')).toHaveLength(3)
		await userEvent.click(within(document.querySelector('.gdb-detail-artwork')! as HTMLElement).getByRole('button', { name: /Hero image/ }))
		const editor = within(screen.getByRole('dialog', { name: 'Edit game' }))
		expect(editor.getByRole('tab', { name: 'Artwork' })).toHaveAttribute('aria-selected', 'true')
		expect(editor.getByLabelText('Hero image')).toHaveFocus()
		expect(mocks.update).not.toHaveBeenCalled()
	})
	it('retains the direct favorite operation without opening a second editor', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: 'Mark as favorite' }))
		await waitFor(() => expect(mocks.update).toHaveBeenCalledWith(game.id, { favorite: true }))
		expect(document.querySelectorAll('dialog[open]')).toHaveLength(1)
	})
	it('does not write an editor draft on cancel', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') })
		fireEvent.change(within(editor).getByLabelText(i18n.t('gallery.detail.notes')), { target: { value: 'Cancelled' } })
		await userEvent.click(within(editor).getByRole('button', { name: i18n.t('gallery.common.cancel') }))
		expect(mocks.update).not.toHaveBeenCalled()
		expect(screen.queryByRole('dialog', { name: i18n.t('gallery.detail.edit') })).not.toBeInTheDocument()
		expect(screen.getByText('Before')).toBeInTheDocument()
	})
	it('saves only edited fields rather than resubmitting metadata and calculated score', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') })
		fireEvent.change(within(editor).getByLabelText(i18n.t('gallery.detail.notes')), { target: { value: 'After' } })
		await userEvent.click(within(editor).getByRole('button', { name: i18n.t('gallery.detail.save') }))
		await waitFor(() => expect(mocks.update).toHaveBeenCalledWith(501, { comment: 'After' }))
		expect(mocks.update).toHaveBeenCalledOnce()
	})
	it('does not send an empty patch when saving an untouched editor', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		await userEvent.click(within(screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') })).getByRole('button', { name: i18n.t('gallery.detail.save') }))
		expect(mocks.update).not.toHaveBeenCalled()
	})
	it('retains the editor and its draft if saving fails', async () => {
		mocks.update.mockRejectedValueOnce(new Error('offline'))
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') })
		fireEvent.change(within(editor).getByLabelText(i18n.t('gallery.detail.notes')), { target: { value: 'Keep my draft' } })
		await userEvent.click(within(editor).getByRole('button', { name: i18n.t('gallery.detail.save') }))
		await waitFor(() => expect(within(editor).getByRole('alert')).toBeInTheDocument())
		expect(within(editor).getByLabelText(i18n.t('gallery.detail.notes'))).toHaveValue('Keep my draft')
	})
	it('has no classic editor, compatibility sheet, or duplicate provider entry', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.gameOptions') }))
		expect(screen.queryByText(/classic editor|provider tools|editor clásico/i)).not.toBeInTheDocument()
		expect(document.querySelector('.gdb-legacy-tools')).not.toBeInTheDocument()
		expect(document.querySelectorAll('dialog[open]')).toHaveLength(1)
	})
	it('exposes the original image searches in the new editor without saving on search or cancel', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = within(screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') }))
		await userEvent.click(editor.getByRole('tab', { name: i18n.t('gallery.detail.images') }))
		for (const [field, additive] of [['Logo', 'logo'], ['Hero', 'header'], ['Cover', 'cover art']]) {
			const label = i18n.t('gallery.detail.searchProvider', { field: i18n.t(`game.details.field${field}`), provider: 'Google Images' })
			const link = editor.getByRole('link', { name: label })
			expect(link).toHaveAttribute('href', `https://www.google.com/search?tbm=isch&q=${encodeURIComponent(`"${game.name}" ${additive}`)}`)
			expect(link).toHaveAttribute('target', '_blank')
			expect(link).toHaveAttribute('rel', 'noopener noreferrer')
		}
		await userEvent.click(editor.getByRole('button', { name: i18n.t('gallery.common.cancel') }))
		expect(mocks.update).not.toHaveBeenCalled()
	})
	it('researches the current draft title and critic provider rather than the original game', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = within(screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') }))
		await userEvent.click(editor.getByRole('tab', { name: i18n.t('gallery.detail.game') }))
		fireEvent.change(editor.getByLabelText(i18n.t('gallery.create.titleLabel')), { target: { value: 'New & draft' } })
		fireEvent.change(editor.getByLabelText(i18n.t('game.details.fieldCriticLogo')), { target: { value: 'OpenCritic' } })
		expect(editor.getByRole('link', { name: /Search Critic.*OpenCritic/ })).toHaveAttribute('href', `https://www.google.com/search?q=${encodeURIComponent('site:opencritic.com New & draft')}`)
		expect(editor.getByRole('link', { name: /Search Main story on HowLongToBeat/ })).toHaveAttribute('href', `https://howlongtobeat.com/?q=${encodeURIComponent('New & draft')}`)
		await userEvent.click(editor.getByRole('tab', { name: i18n.t('gallery.detail.images') }))
		expect(editor.getByRole('link', { name: /Search Cover.*Google Images/ })).toHaveAttribute('href', `https://www.google.com/search?tbm=isch&q=${encodeURIComponent('"New & draft" cover art')}`)
		expect(mocks.update).not.toHaveBeenCalled()
	})
	it('keeps research links directly available on the detail without opening the classic editor', async () => {
		renderDetails()
		await waitFor(() => expect(screen.getByRole('button', { name: 'Add to Focus' })).toBeEnabled())
		expect(screen.getByRole('link', { name: /Search Critic.*Metacritic/ })).toHaveAttribute('href', `https://www.metacritic.com/search/${encodeURIComponent(game.name)}/`)
		expect(screen.getByRole('link', { name: /Search Main story on HowLongToBeat/ })).toHaveAttribute('href', `https://howlongtobeat.com/?q=${encodeURIComponent(game.name)}`)
		expect(screen.getByRole('link', { name: /Search Cover.*Google Images/ })).toBeVisible()
		expect(screen.queryByTestId('provider-tools')).not.toBeInTheDocument()
		expect(mocks.update).not.toHaveBeenCalled()
	})
	it('retains the original parent confirmation flow without adding a duplicate prompt', async () => {
		const onDelete = vi.fn()
		renderDetails(onDelete)
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.gameOptions') }))
		await userEvent.click(screen.getByRole('button', { name: i18n.t('game.details.deleteGame') }))
		expect(onDelete).toHaveBeenCalledWith(game)
		expect(mocks.remove).not.toHaveBeenCalled()
		expect(screen.queryByRole('alertdialog')).not.toBeInTheDocument()
	})
	it('requires its own confirmation when no parent deletion handler is supplied', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.gameOptions') }))
		await userEvent.click(screen.getByRole('button', { name: i18n.t('game.details.deleteGame') }))
		expect(mocks.remove).not.toHaveBeenCalled()
		await userEvent.click(within(screen.getByRole('alertdialog')).getByRole('button', { name: i18n.t('common.delete') }))
		await waitFor(() => expect(mocks.remove).toHaveBeenCalledWith(game.id))
	})
	it('retains the draft across all four tabs and saves a dirty patch from a different tab', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') }),
			ui = within(editor)
		fireEvent.change(ui.getByLabelText(i18n.t('gallery.detail.notes')), { target: { value: 'Across tabs' } })
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.game') }))
		fireEvent.change(ui.getByLabelText(i18n.t('gallery.create.titleLabel')), { target: { value: 'Renamed' } })
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.images') }))
		fireEvent.change(ui.getByLabelText(i18n.t('game.details.fieldCover')), { target: { value: 'https://example.com/new-cover.png' } })
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.studio') }))
		fireEvent.change(ui.getByRole('textbox', { name: i18n.t('gallery.detail.studio') }), { target: { value: 'Explicit studio' } })
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.personal') }))
		expect(ui.getByLabelText(i18n.t('gallery.detail.notes'))).toHaveValue('Across tabs')
		await userEvent.click(ui.getByRole('button', { name: i18n.t('gallery.detail.save') }))
		await waitFor(() =>
			expect(mocks.update).toHaveBeenCalledWith(501, { name: 'Renamed', comment: 'Across tabs', cover: 'https://example.com/new-cover.png', developer: 'Explicit studio' })
		)
		expect(mocks.update).toHaveBeenCalledOnce()
	})
	it('returns to an invalid hidden tab instead of saving its malformed number', async () => {
		renderDetails()
		await userEvent.click(screen.getByRole('button', { name: i18n.t('gallery.detail.edit') }))
		const editor = screen.getByRole('dialog', { name: i18n.t('gallery.detail.edit') }),
			ui = within(editor)
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.game') }))
		fireEvent.change(ui.getByLabelText(i18n.t('gallery.detail.grade')), { target: { value: '101' } })
		await userEvent.click(ui.getByRole('tab', { name: i18n.t('gallery.detail.personal') }))
		await userEvent.click(ui.getByRole('button', { name: i18n.t('gallery.detail.save') }))
		expect(mocks.update).not.toHaveBeenCalled()
		expect(ui.getByRole('tab', { name: i18n.t('gallery.detail.game') })).toHaveAttribute('aria-selected', 'true')
		expect(ui.getByLabelText(i18n.t('gallery.detail.grade'))).toHaveAttribute('aria-invalid', 'true')
	})
})
